import { useState } from 'react';
import { api } from '../api';
import type { RiskExplanation } from '../types';

type State =
  | { status: 'idle' }
  | { status: 'loading' }
  | { status: 'done'; explanation: RiskExplanation }
  | { status: 'error'; message: string };

/** "Explain with AI" button with loading and error states. */
export function ExplainPanel({ itemId, aiEnabled }: { itemId: string; aiEnabled: boolean }) {
  const [state, setState] = useState<State>({ status: 'idle' });

  async function explain() {
    setState({ status: 'loading' });
    try {
      setState({ status: 'done', explanation: await api.explainItem(itemId) });
    } catch (error) {
      setState({ status: 'error', message: error instanceof Error ? error.message : 'Something went wrong.' });
    }
  }

  return (
    <section className="explain" aria-live="polite">
      <div className="explain-head">
        <h3>Explanation</h3>
        {state.status !== 'done' && (
          <button className="btn-primary" onClick={explain} disabled={state.status === 'loading'}>
            {state.status === 'loading' ? <><span className="spinner" aria-hidden="true" /> Explaining…</> : 'Explain with AI'}
          </button>
        )}
      </div>

      {state.status === 'idle' && (
        <p className="muted small">
          {aiEnabled
            ? 'Get a plain-language explanation and fix steps. Only metadata is sent to the AI — no names or email addresses.'
            : 'No AI key is configured, so the built-in rule-based explanations are used.'}
        </p>
      )}

      {state.status === 'error' && (
        <div className="alert" role="alert">
          <span>{state.message}</span>
          <button className="btn-link" onClick={explain}>Try again</button>
        </div>
      )}

      {state.status === 'done' && (
        <div className="explain-body">
          <p>{state.explanation.explanation}</p>
          <h4>Why it matters</h4>
          <p>{state.explanation.businessRisk}</p>
          {state.explanation.fixSteps.length > 0 && (
            <>
              <h4>How to fix it</h4>
              <ol>
                {state.explanation.fixSteps.map((step) => <li key={step}>{step}</li>)}
              </ol>
            </>
          )}
          <p className="muted small">Generated by {state.explanation.generatedBy}</p>
        </div>
      )}
    </section>
  );
}
